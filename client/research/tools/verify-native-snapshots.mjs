import assert from 'node:assert/strict';
import fs from 'node:fs';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
const {NativeSnapshotState,NativeMissingSnapshot,NativeSchema,NativeEntityFields}=await import(pathToFileURL(resolve(process.argv[2])).href);
const schema=new NativeSchema({symbols:['Root'],fields:[],serializers:[{serializer_name_sym:0,serializer_version:0,fields_index:[]}]},[{class_id:0,network_name:'Root'}],1);
const fields=NativeEntityFields.empty(schema,0);
const entity=(id=0,serial=1)=>({id,classId:0,serial,fields});
const h=(tick,deltaFrom,extra={})=>({tick,serverTick:tick,baseline:0,updateBaseline:false,...(deltaFrom===undefined?{}:{deltaFrom}),...extra});
let checks=0;const check=fn=>{fn();checks++;};
const state=new NativeSnapshotState(3);
check(()=>assert.equal(state.transact(h(2,1),()=>{throw Error('must not decode');}),null));
let escaped;
const receipt=state.transact(h(10,undefined,{updateBaseline:true}),d=>{escaped=d;d.put(entity());d.enter(0);d.saveBaseline(0);});
check(()=>assert.deepEqual(receipt,{epoch:0,tick:10,full:true,baselineAck:0}));
check(()=>assert.throws(()=>escaped.put(entity(1)),/Closed/));
check(()=>assert.equal(state.getEntity(0).serial,1));
check(()=>assert.equal(state.waitingFull,false));
check(()=>assert.throws(()=>state.transact(h(11,9),()=>{}),NativeMissingSnapshot));
check(()=>assert.equal(state.lastTick,10));
check(()=>assert.throws(()=>state.transact(h(11,10,{baseline:1,updateBaseline:true}),d=>{
 assert.equal(d.baseline(0,0),fields);d.put(entity(0,2));d.leave(0,true);throw Error('truncated payload');
}),/truncated payload/));
check(()=>assert.equal(state.getEntity(0).serial,1));
check(()=>assert.equal(state.hasFrame(11),false));
state.transact(h(11,10,{baseline:1}),d=>{assert.equal(d.baseline(0,0),fields);d.put(entity(0,3));d.enter(0);});
check(()=>assert.equal(state.getEntity(0).serial,3));
state.transact(h(12,10),d=>{assert.equal(d.get(0).serial,3);d.enter(0);}); // Not stale properties at tick10.
check(()=>assert.equal(state.hasFrame(10),true));
state.transact(h(13,11),()=>{});
check(()=>assert.equal(state.hasFrame(10),false));
check(()=>assert.equal(state.hasFrame(11),true));
state.transact(h(14),d=>{assert.equal(d.baseline(0,0),undefined);d.enter(0);});
check(()=>assert.equal(state.epoch,0));
check(()=>assert.equal(state.hasFrame(12),true));
state.transact(h(15,14,{baseline:1}),d=>assert.equal(d.baseline(0,0),undefined));
const back=state.transact(h(5),d=>{d.enter(0);});
check(()=>assert.equal(back.epoch,1));
check(()=>assert.equal(state.hasFrame(14),false));
check(()=>assert.equal(state.hasFrame(5),true));
check(()=>assert.throws(()=>state.transact(h(6,5),d=>{d.put(entity(0,4));state.recover();}),/Retired/));
check(()=>assert.equal(state.getEntity(0).serial,3));
check(()=>assert.equal(state.lastTick,-1));
check(()=>assert.equal(state.epoch,2));
check(()=>assert.equal(state.transact(h(7,5),()=>{}),null));
state.transact(h(8),d=>{d.put(entity(1));d.enter(1);d.removeAbsent();});
check(()=>assert.equal(state.getEntity(0),undefined));
check(()=>assert.equal(state.entityCount,1));
check(()=>assert.throws(()=>state.transact(h(9,8),()=>{state.transact(h(9,8),()=>{});}),/Nested/));
check(()=>assert.equal(state.lastTick,8));
check(()=>assert.throws(()=>state.transact(h(9,8,{serverTick:10}),()=>{}),/receive tick/));
check(()=>assert.throws(()=>state.transact(h(9,9),()=>{}),/delta reference/));
check(()=>assert.throws(()=>state.transact(h(9,8),d=>d.put(entity(16384))),/index/));
check(()=>assert.throws(()=>state.transact(h(9,8),d=>d.put(entity(0,131072))),/identity/));
state.reset();
check(()=>assert.equal(state.entityCount,0));
check(()=>assert.equal(state.waitingFull,true));
const anchored=new NativeSnapshotState(3);
anchored.transact(h(100),d=>{d.put(entity());d.enter(0);});
for(let tick=101;tick<=300;tick++)anchored.transact(h(tick,100),d=>d.enter(0));
check(()=>assert.equal(anchored.hasFrame(100),true));
check(()=>assert.equal(anchored.hasFrame(298),false));
check(()=>assert.equal(anchored.hasFrame(299),true));
check(()=>assert.equal(anchored.hasFrame(300),true));
anchored.transact(h(301,299),d=>d.enter(0));
check(()=>assert.equal(anchored.hasFrame(100),false));
check(()=>assert.equal(anchored.lastTick,301));
check(()=>assert.throws(()=>anchored.transact(h(302,298),()=>{}),NativeMissingSnapshot));
const delayed=new NativeSnapshotState();
delayed.transact(h(100),d=>{d.put(entity());d.enter(0);});
for(let tick=101;tick<=700;tick++)delayed.transact(h(tick,Math.max(100,tick-134)),d=>d.enter(0));
check(()=>assert.equal(delayed.lastTick,700));
check(()=>assert.equal(delayed.hasFrame(566),true));
check(()=>assert.equal(delayed.hasFrame(565),false));
const output={scope:'Isolated forward snapshot transaction owner; no wire/runtime/live acceptance',checks,passed:true};
fs.writeFileSync((process.env.GOTV_RESEARCH_ROOT??'.agent-tmp/gotv-research-plan/')+'native-snapshot-transactions.json',JSON.stringify(output,null,2)+'\n');
console.log(output);
